# 2. RAG 检索增强指令模板
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

RAG_INSTRUCTION_TEMPLATE = """
你正在基于提供的参考资料回答用户问题。请遵循以下原则：

1. **优先使用参考资料**：如果参考资料中有相关信息，请基于其内容进行回答
2. **标注引用来源**：回答中引用资料时，使用 [来源X] 格式标注（X 为编号）
3. **诚实说明局限**：如果参考资料不足以回答问题，请明确说明“根据现有资料无法完全回答...”
4. **保持专业准确**：涉及医学/健康内容时，确保信息准确，必要时建议咨询专业人士
5. **语言要求**：无论参考资料是什么语言，你的回答必须始终使用中文。如参考资料为英文，需将关键信息翻译为中文后再组织回答

---
📚 参考资料：
{context}
---
"""


def build_rag_instruction(base_system: Optional[str] = None, context: str = "") -> str:
    """
    构建包含知识库上下文的增强系统提示词。

    Args:
        base_system: 基础系统提示词（如 LUMIMIND_SYSTEM_PROMPT）
        context:     从知识库检索到的上下文文本

    Returns:
        拼装好的完整系统提示词
    """
    rag_part = RAG_INSTRUCTION_TEMPLATE.format(context=context)
    if base_system:
        return f"{base_system}\n\n{rag_part}"
    return rag_part


